#!/usr/bin/env node
/**
 * Generate a .env with fresh secrets.
 *
 * This exists so "clone and run" works without shipping real secrets in the
 * repo and without any secret having a fallback default in application code.
 * Run it again with --force to rotate everything (which invalidates all
 * existing sessions and makes sealed email fields unreadable).
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, '.env');
const force = process.argv.includes('--force');

if (existsSync(target) && !force) {
  console.log('.env already exists — leaving it alone (use --force to regenerate).');
  process.exit(0);
}

const b64 = (n) => randomBytes(n).toString('base64');
const { publicKey, privateKey } = generateKeyPairSync('ed25519');
const pemToB64 = (pem) => Buffer.from(pem).toString('base64');

const body = `# Generated by \`pnpm setup\` — do not commit.
# Regenerate with: pnpm setup --force  (invalidates sessions and sealed fields)

NODE_ENV=development
PORT=4000
LOG_LEVEL=debug

# Local dev points at the Docker mongo; compose overrides this to mongodb://mongo:27017/rtc
MONGO_URI=mongodb://localhost:27017/rtc
# Host port for the Docker MongoDB. Change this (and the port in
# MONGO_URI above) if another project already has 27017 bound.
MONGO_HOST_PORT=27017

# Single origin: the Vite dev server proxies /api and /socket.io to PORT above.
APP_ORIGIN=http://localhost:5173
ALLOWED_ORIGINS=http://localhost:5173,http://localhost:8080
COOKIE_SAMESITE=strict
TRUST_PROXY=0

# Ed25519 keypair for access tokens (base64-encoded PEM).
JWT_PRIVATE_KEY_B64=${pemToB64(privateKey.export({ type: 'pkcs8', format: 'pem' }))}
JWT_PUBLIC_KEY_B64=${pemToB64(publicKey.export({ type: 'spki', format: 'pem' }))}
JWT_KID=k1

CSRF_KEY=${b64(32)}
PASSWORD_PEPPER=${b64(32)}
DATA_ENCRYPTION_KEY=${b64(32)}
BLIND_INDEX_KEY=${b64(32)}
IP_HASH_KEY=${b64(32)}
ENUM_KEY=${b64(32)}

ACCESS_TOKEN_TTL_S=600
REFRESH_TOKEN_TTL_S=1209600
REFRESH_ABSOLUTE_TTL_S=2592000

MAX_UPLOAD_BYTES=26214400
MAX_CALL_PARTICIPANTS=4

# Optional TURN relay. Without it, mesh calls reveal each participant's IP to
# every other participant — inherent to peer-to-peer, surfaced in the UI.
# TURN_HOST=localhost
# TURN_STATIC_AUTH_SECRET=
TURN_TTL_S=300

# Production single-origin mode: this process also serves the built SPA.
SERVE_STATIC=false
WEB_DIST_DIR=../web/dist

# Integration tests and repeated local smoke runs only; refused in production.
RATE_LIMIT_DISABLED=false

SEED_PASSWORD=demo1234
DEMO_MODE=true
`;

writeFileSync(target, body, { mode: 0o600 });
console.log(`Wrote ${target} with freshly generated secrets.`);
